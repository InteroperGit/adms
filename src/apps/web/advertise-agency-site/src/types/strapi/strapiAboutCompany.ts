import {Entity} from "@/types/base";
import {ImageMeta} from "@/types/image";

/**
 * Модель данных раздела "О компании", получаемая из Strapi.
 */
export interface StrapiAboutCompany extends Entity {
    /**
     * Заголовок раздела, например: "О компании"
     */
    title: string;

    /**
     * Уникальный slug для идентификации записи, например: "about-company"
     */
    slug: string;

    /**
     * Основное описание компании. Обычно содержит абзац или два текста.
     */
    description: string;

    /**
     * Особенности или ключевые моменты о компании, представленные как массив строк.
     * Например: ["Работаем с 2009 года", "Собственное производство", "Гарантия 5 лет"]
     */
    highlights: string[];

    /**
     * Список изображений, связанных с разделом (например, фотографии производства или команды).
     */
    images: ImageMeta[];
}
