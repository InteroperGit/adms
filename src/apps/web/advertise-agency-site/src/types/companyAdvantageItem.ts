import {Entity} from "@/types/base";

/**
 * Интерфейс описывает структуру одного элемента "преимущества компании".
 * Эти данные могут использоваться для отображения блоков преимуществ на лендинге,
 * странице "О компании" или в маркетинговых секциях сайта.
 */
export interface CompanyAdvantageItem extends Entity {
    /**
     * Заголовок преимущества.
     * Например: "Собственное производство", "15 лет на рынке", "Гарантия качества"
     */
    title: string;

    /**
     * Уникальный человеко-читаемый идентификатор,
     * используется для генерации ссылок или якорей.
     * Обычно формируется на основе title.
     * Например: "sobstvennoe-proizvodstvo"
     */
    slug: string;

    /**
     * Расширенное описание преимущества.
     * Может содержать объяснение, почему это преимущество важно для клиента.
     */
    description: string;
}
