import {ArticleCodeBlock} from "@/types/article";
import {JSX} from "react";

/**
 * Компонент для отображения блоков кода с подсветкой синтаксиса и опциональными номерами строк.
 * Предназначен для использования в статьях, блогах, документации и других контентных блоках, где необходимо показать фрагменты кода.
 *
 * Зачем нужен:
 * - Отображает фрагмент кода с возможностью указания языка программирования.
 * - Поддерживает отображение номеров строк, что удобно для примеров кода и обучающих материалов.
 * - Использует стили для улучшенной визуализации кода, включая цветовую подсветку синтаксиса и выделение языка.
 *
 * Пропсы:
 * - `code`: сам код, который будет отображаться внутри блока.
 * - `language`: язык программирования, который используется для подсветки синтаксиса (например, "javascript", "python").
 * - `showLineNumbers`: если `true`, отображаются номера строк в коде.
 *
 * Особенности:
 * - Возможность включить/выключить отображение номеров строк с помощью флага `showLineNumbers`.
 * - Подсветка синтаксиса на основе языка программирования (например, для JavaScript, Python, и т. д.).
 * - Если язык не указан, код отображается как обычный текст (plaintext).
 *
 * Где использовать:
 * - В статьях или блогах для вставки примеров кода.
 * - В технической документации для демонстрации фрагментов программ.
 * - В обучающих материалах и на образовательных платформах для отображения примеров программирования.
 */
const CodeBlockArticleBlock = ({
                                       code,
                                       language,
                                       showLineNumbers = false
                                   }: ArticleCodeBlock): JSX.Element => {
    return (
        <div className="my-6 bg-gray-800 rounded-lg overflow-hidden">
            {language && (
                <div className="px-4 py-2 text-xs text-gray-300 bg-gray-700">
                    {language}
                </div>
            )}
            <pre className={`p-4 overflow-x-auto text-sm ${showLineNumbers ? 'line-numbers' : ''}`}>
                <code className={`language-${language || 'plaintext'}`}>
                    {code}
                </code>
            </pre>
        </div>
    );
};

export default CodeBlockArticleBlock;
